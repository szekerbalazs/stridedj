"""Outputs of the data-science layer: duration estimates, race predictions and cadence targets.

These are the *aggregates* the LLM is allowed to see (through tool results).
"""

from __future__ import annotations

from enum import StrEnum
from typing import Self

from pydantic import Field, model_validator

from stridedj.domain.base import Frozen
from stridedj.domain.runs import RunType

SLOT_GRANULARITY_MIN = 15


class EstimateMethod(StrEnum):
    """Which regime produced a duration estimate (shown to the user, so the agent can be honest about uncertainty)."""

    RECENT_SIMILAR = "recent_similar"  # enough recent runs of this type and distance: empirical quantiles
    REGRESSION = "regression"  # extrapolated from recent runs with the personal model
    RIEGEL = "riegel"  # textbook power law from the best recent anchor run
    DEFAULT = "default"  # no usable history: a conservative default pace


class DurationEstimate(Frozen):
    run_type: RunType
    distance_km: float = Field(gt=0, le=100)
    method: EstimateMethod
    n_runs_used: int = Field(ge=0)
    p50_min: float = Field(gt=0, description="median predicted running time")
    p80_min: float = Field(
        gt=0, description="80th percentile: the newsvendor-optimal slot length for 4:1 overrun:idle costs"
    )
    slot_min: int = Field(gt=0, description="calendar slot: p80 + buffer, rounded UP to a multiple of 15 minutes")
    note: str = Field(
        description="one sentence, generated by code, explaining the regime (e.g. 'extrapolated from 14 runs')"
    )

    @model_validator(mode="after")
    def _consistent(self) -> Self:
        if self.p80_min < self.p50_min:
            raise ValueError("p80 must be >= p50")
        if self.slot_min % SLOT_GRANULARITY_MIN:
            raise ValueError(f"slot_min must be a multiple of {SLOT_GRANULARITY_MIN}")
        if self.slot_min < self.p80_min:
            raise ValueError("slot_min must cover p80")
        return self


class RacePrediction(Frozen):
    distance_km: float = Field(gt=0, le=100)
    predicted_min: float = Field(gt=0)
    method: EstimateMethod
    n_runs_used: int = Field(ge=0)


class CadenceTarget(Frozen):
    run_type: RunType
    spm: float = Field(gt=100, lt=250, description="target steps per minute")
    n_runs: int = Field(ge=0, description="runs the target is based on (0 = population default)")
    lookback_days: int = Field(gt=0)
    trend_spm_per_30d: float | None = Field(
        default=None, description="slope of cadence over time; None if too few runs"
    )
