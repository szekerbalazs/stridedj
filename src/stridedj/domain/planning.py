"""Outputs of the data-science layer: duration estimates, race predictions and cadence targets.

These are the *aggregates* the LLM is allowed to see (through tool results).
"""

from __future__ import annotations

from enum import StrEnum
from typing import Self

from pydantic import Field, model_validator

from stridedj.domain.base import Frozen
from stridedj.domain.runs import RunType

SLOT_GRANULARITY_MIN = 5  # slot LENGTH; slot STARTS stay on the quarter-hour grid (cal/slots.py)


class EstimateMethod(StrEnum):
    """Which regime produced a duration estimate (shown to the user, so the agent can be honest about uncertainty)."""

    RECENT_SIMILAR = "recent_similar"  # enough recent runs of this type and distance: empirical quantiles
    REGRESSION = "regression"  # extrapolated from recent runs with the personal model
    RIEGEL = "riegel"  # textbook power law from the best recent anchor run
    DEFAULT = "default"  # no usable history: a conservative default pace
    SESSION = "session"  # an interval session: its own structure (warm-up, reps at target pace, rests, cool-down)


class DurationEstimate(Frozen):
    run_type: RunType
    distance_km: float = Field(gt=0, le=100)
    method: EstimateMethod
    n_runs_used: int = Field(ge=0)
    p50_min: float = Field(gt=0, description="median predicted running time")
    p80_min: float = Field(
        gt=0, description="80th percentile: the newsvendor-optimal slot length for 4:1 overrun:idle costs"
    )
    slot_min: int = Field(gt=0, description="calendar slot: p80 + buffer, rounded UP to a multiple of 5 minutes")
    note: str = Field(
        description="one sentence, generated by code, explaining the regime (e.g. 'extrapolated from 14 runs')"
    )

    @model_validator(mode="after")
    def _consistent(self) -> Self:
        if self.p80_min < self.p50_min:
            raise ValueError("p80 must be >= p50")
        if self.slot_min % SLOT_GRANULARITY_MIN:
            raise ValueError(f"slot_min must be a multiple of {SLOT_GRANULARITY_MIN}")
        if self.slot_min < self.p80_min:
            raise ValueError("slot_min must cover p80")
        return self


class RacePrediction(Frozen):
    distance_km: float = Field(gt=0, le=100)
    predicted_min: float = Field(gt=0)
    method: EstimateMethod
    n_runs_used: int = Field(ge=0)


class CadenceTarget(Frozen):
    run_type: RunType
    spm: float = Field(gt=100, lt=250, description="target steps per minute")
    n_runs: int = Field(ge=0, description="runs the target is based on (0 = population default)")
    lookback_days: int = Field(gt=0)
    trend_spm_per_30d: float | None = Field(
        default=None, description="slope of cadence over time; None if too few runs"
    )


class RunningProfile(Frozen):
    """Aggregate view of the user's recent runs of one type (what `get_running_profile` returns to the LLM)."""

    run_type: RunType
    lookback_days: int = Field(gt=0)
    n_runs: int = Field(ge=0)
    median_distance_km: float | None = None
    median_pace_s_per_km: float | None = None
    median_cadence_spm: float | None = None
    last_run_days_ago: int | None = Field(default=None, ge=0)
    pace_trend_s_per_km_per_30d: float | None = Field(default=None, description="negative = getting faster")


class IntervalSessionDistance(Frozen):
    """The total of an interval session ("4x800, 2 km warm-up, 1 km cool-down"), added up by code, not the LLM."""

    total_km: float = Field(gt=0, description="pass this as distance_km")
    warmup_km: float = Field(ge=0)
    work_km: float = Field(gt=0)
    recovery_km: float = Field(ge=0)
    cooldown_km: float = Field(ge=0)
    recovery_assumed: bool = Field(description="True when the runner gave no recovery: standing rests (0 m) assumed")


def format_pace(s_per_km: float) -> str:
    """270.4 → "4:30" (min:s per km)."""
    total = round(s_per_km)
    return f"{total // 60}:{total % 60:02d}"


class IntervalSession(Frozen):
    """An interval session built by code from the runner's targets: distance reps, standing rests. The model refers
    to it by `session_id`; the plan, the proposal card and the calendar event carry it."""

    session_id: str
    kind: str = Field(description="short / medium / pyramid")
    reps_m: tuple[int, ...] = Field(min_length=1)
    target_paces_s_per_km: tuple[float, ...] = Field(min_length=1, description="one per rep")
    rest_s: tuple[int, ...] = Field(description="standing rest after each rep but the last")
    warmup_km: float = Field(ge=0)
    cooldown_km: float = Field(ge=0)
    total_km: float = Field(gt=0, description="warm-up + reps + cool-down (standing rests cover no distance)")
    duration: DurationEstimate

    @model_validator(mode="after")
    def _shape(self) -> Self:
        if len(self.target_paces_s_per_km) != len(self.reps_m) or len(self.rest_s) != len(self.reps_m) - 1:
            raise ValueError("one target pace per rep and one rest between consecutive reps")
        return self

    @property
    def main_set(self) -> str:
        """ "6 × 800 m @ 4:10, 90 s rest" or "400-800-1200-800-400 m @ 3:45/4:10/4:20/4:10/3:45"."""
        if len(set(self.reps_m)) == 1:
            rest = f", {self.rest_s[0]} s rest" if self.rest_s else ""
            pace = format_pace(self.target_paces_s_per_km[0])
            return f"{len(self.reps_m)} × {self.reps_m[0]} m @ {pace}{rest}"
        reps = "-".join(str(r) for r in self.reps_m)
        paces = "/".join(format_pace(p) for p in self.target_paces_s_per_km)
        return f"{reps} m @ {paces}"

    @property
    def outline(self) -> str:
        """The whole session in one line, for the proposal card and the calendar event."""
        parts = []
        if self.warmup_km:
            parts.append(f"{self.warmup_km:g} km warm-up")
        parts.append(f"{self.main_set} (standing rests)" if len(set(self.reps_m)) > 1 else self.main_set + " standing")
        if self.cooldown_km:
            parts.append(f"{self.cooldown_km:g} km cool-down")
        return " · ".join(parts)
