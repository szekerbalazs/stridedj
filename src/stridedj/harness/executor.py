"""Executes an approved `RunPlan`: the ONLY place in the system that writes to the outside world.

* Runs only with a plan returned by `ApprovalStore.consume` (bound, single-use, unexpired, same user).
* All text written to Spotify/Google comes from fixed templates filled with numbers from the plan. The LLM writes
  nothing that leaves the system: no titles, descriptions, URLs or attendees (an exfiltration channel closed by design).
* Idempotent: the calendar event id is derived from the plan hash (a retry can't create a duplicate), and executed
  plans are remembered (a second execution returns the first result).
* Partial failures are reported, not hidden: if the playlist fails, the event is still created, and vice versa.
* A created playlist is recorded in the playlist history (ids only), so the next drafts can rotate songs.
"""

from __future__ import annotations

import logging
from zoneinfo import ZoneInfo

from stridedj.cal.gcal import event_id_for
from stridedj.domain import ExecutionResult, PlanId, RunPlan, RunType
from stridedj.errors import StrideDJError
from stridedj.ports import CalendarPort, PlaylistHistoryPort, PlaylistWriterPort

log = logging.getLogger(__name__)

RUN_TYPE_LABEL: dict[RunType, str] = {
    RunType.Z1: "Z1 recovery",
    RunType.Z2: "Z2 easy",
    RunType.Z3: "Z3 tempo",
    RunType.Z4: "Z4 threshold",
    RunType.Z5: "Z5",
    RunType.INTERVALS: "intervals",
}


def event_title(plan: RunPlan) -> str:
    return f"🏃 {plan.distance_km:g} km {RUN_TYPE_LABEL[plan.run_type]} run"


def event_description(plan: RunPlan, playlist_url: str | None) -> str:
    lines = [
        "Planned by StrideDJ.",
        f"Expected running time: ~{plan.duration.p50_min:.0f} min (80% within {plan.duration.p80_min:.0f} min).",
        f"Cadence target: {plan.cadence.spm:.0f} steps/min.",
    ]
    if playlist_url:
        lines.append(f"Playlist: {playlist_url}")
    return "\n".join(lines)


def playlist_name(plan: RunPlan, tz: ZoneInfo) -> str:
    day = plan.slot.start.astimezone(tz).strftime("%a %d %b")
    return f"StrideDJ · {plan.distance_km:g} km {plan.run_type.value.upper()} · {day}"


class PlanExecutor:
    def __init__(
        self,
        *,
        calendar: CalendarPort,
        playlists: PlaylistWriterPort,
        tz: ZoneInfo,
        history: PlaylistHistoryPort | None = None,
    ) -> None:
        self._calendar = calendar
        self._playlists = playlists
        self._tz = tz
        self._history = history
        self._done: dict[PlanId, ExecutionResult] = {}

    async def execute(self, plan: RunPlan) -> ExecutionResult:
        if plan.plan_id in self._done:
            return self._done[plan.plan_id]
        errors: list[str] = []

        playlist_url: str | None = None
        if plan.playlist is not None and plan.playlist.track_ids:
            try:
                playlist_url = await self._playlists.create_private_playlist(
                    name=playlist_name(plan, self._tz),
                    description=f"Matched to {plan.cadence.spm:.0f} steps/min. Generated by StrideDJ.",
                    track_ids=plan.playlist.track_ids,
                )
            except StrideDJError as exc:
                log.warning("playlist creation failed: %s", exc)
                errors.append("The playlist could not be created.")
            else:
                self._remember(plan)

        event_id: str | None = None
        try:
            event_id = await self._calendar.insert_event(
                event_id=event_id_for(plan.content_hash()),
                slot=plan.slot,
                title=event_title(plan),
                description=event_description(plan, playlist_url),
            )
        except StrideDJError as exc:
            log.warning("calendar insert failed: %s", exc)
            errors.append("The calendar event could not be created.")

        result = ExecutionResult(
            plan_id=plan.plan_id,
            calendar_event_id=event_id,
            playlist_url=playlist_url,
            playlist_draft_id=plan.playlist.draft_id if playlist_url and plan.playlist else None,
            errors=tuple(errors),
        )
        if not errors:
            self._done[plan.plan_id] = result
        return result

    def _remember(self, plan: RunPlan) -> None:
        """Record the created playlist for rotation. Best effort: a local DB problem must not fail an approval."""
        if self._history is None or plan.playlist is None:
            return
        try:
            self._history.record_created(plan.playlist)
        except Exception:
            log.exception("could not record the created playlist")
